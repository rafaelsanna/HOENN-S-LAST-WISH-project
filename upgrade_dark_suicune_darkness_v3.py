class UpgradeError(RuntimeError):
    pass

def log(msg=""):
    print(msg, flush=True)

def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def sha256_file(path: Path):
    if not path.is_file():
        return None
    h = hashlib.sha256()
    with path.open("rb") as f:
        for block in iter(lambda: f.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()

def decode_payload(s: str) -> bytes:
    return zlib.decompress(base64.b64decode(s.encode("ascii")))

def atomic_write(path: Path, data: bytes):
    path.parent.mkdir(parents=True, exist_ok=True)
    mode = path.stat().st_mode if path.exists() else None
    fd, tmp = tempfile.mkstemp(prefix=path.name + ".tmp.", dir=str(path.parent))
    tmp_path = Path(tmp)
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        if mode is not None:
            os.chmod(tmp_path, mode)
        os.replace(tmp_path, path)
    finally:
        if tmp_path.exists():
            tmp_path.unlink()

def validate_root(root: Path):
    for rel in ("Makefile", "src", "include", "graphics"):
        if not (root / rel).exists():
            raise UpgradeError(
                "Nao parece ser a raiz do pokeemerald-expansion: "
                f"faltando {rel}"
            )
    for rel in (TARGET_SCENE, TARGET_WEATHER, TARGET_EFFECT, TARGET_CONSTANTS):
        if not (root / rel).is_file():
            raise UpgradeError(f"Arquivo obrigatorio nao encontrado: {rel}")

def verify_embedded_payloads():
    values = [
        ("scene", decode_payload(PAYLOAD_SCENE), NEW_SCENE_SHA),
        ("weather", decode_payload(PAYLOAD_WEATHER), NEW_WEATHER_SHA),
        ("effect", decode_payload(PAYLOAD_EFFECT), NEW_EFFECT_SHA),
    ]
    for name, data, expected in values:
        got = sha256_bytes(data)
        if got != expected:
            raise UpgradeError(
                f"Payload embutido corrompido ({name}): {got} != {expected}"
            )
    return values[0][1], values[1][1], values[2][1]

def patch_weather_constants(text: str):
    if "WEATHER_CONCERT_LIGHTS" not in text:
        raise UpgradeError(
            "include/constants/weather.h nao contem WEATHER_CONCERT_LIGHTS. "
            "Este patch foi preparado para a arvore custom que voce enviou."
        )

    def collect_numeric_ids(src):
        ids = []
        for m in re.finditer(
            r"^\s*#define\s+(WEATHER_[A-Z0-9_]+)\s+(\d+)\b",
            src,
            re.M,
        ):
            name = m.group(1)
            if name == "WEATHER_COUNT":
                continue
            ids.append((name, int(m.group(2))))
        return ids

    ids = collect_numeric_ids(text)
    if not ids:
        raise UpgradeError("Nao consegui detectar os IDs WEATHER_* numericos.")

    existing_dark = re.search(
        r"^\s*#define\s+WEATHER_DARKNESS\s+(\d+)\b", text, re.M
    )
    existing_rain = re.search(
        r"^\s*#define\s+WEATHER_DARKNESS_RAIN\s+(\d+)\b", text, re.M
    )

    if existing_dark and existing_rain:
        dark_id = int(existing_dark.group(1))
        rain_id = int(existing_rain.group(1))
        max_id = max(v for _, v in collect_numeric_ids(text))
    elif existing_dark or existing_rain:
        raise UpgradeError(
            "Somente um dos defines DARKNESS/DARKNESS_RAIN existe."
        )
    else:
        max_id = max(v for _, v in ids)
        dark_id = max_id + 1
        rain_id = max_id + 2
        count_match = re.search(
            r"^(\s*#define\s+WEATHER_COUNT\s+)(\d+)(.*)$",
            text,
            re.M,
        )
        if not count_match:
            raise UpgradeError("WEATHER_COUNT numerico nao encontrado.")
        insertion = (
            f"#define WEATHER_DARKNESS                {dark_id}\n"
            f"#define WEATHER_DARKNESS_RAIN           {rain_id}\n"
        )
        text = text[:count_match.start()] + insertion + text[count_match.start():]
        max_id = rain_id

    required_count = max(max_id, dark_id, rain_id) + 1

    def replace_count(m):
        current = int(m.group(2))
        return m.group(1) + str(max(current, required_count)) + m.group(3)

    text, n = re.subn(
        r"^(\s*#define\s+WEATHER_COUNT\s+)(\d+)(.*)$",
        replace_count,
        text,
        count=1,
        flags=re.M,
    )
    if n != 1:
        raise UpgradeError("Falha ao atualizar WEATHER_COUNT.")

    return text, dark_id, rain_id, required_count

def backup(root: Path, rels, dry_run=False):
    stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    dest = root / BACKUP_ROOT / stamp
    manifest = {
        "created_at": dt.datetime.now().isoformat(timespec="seconds"),
        "files": [],
    }
    for rel in rels:
        p = root / rel
        manifest["files"].append({
            "path": rel.as_posix(),
            "exists": p.exists(),
            "sha256": sha256_file(p) if p.is_file() else None,
        })
    if dry_run:
        log(f"[dry-run] backup seria: {dest.relative_to(root)}")
        return dest

    dest.mkdir(parents=True, exist_ok=False)
    for entry in manifest["files"]:
        if not entry["exists"]:
            continue
        rel = Path(entry["path"])
        src = root / rel
        out = dest / rel
        out.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, out)
    (dest / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    return dest

def latest_backup(root: Path):
    parent = root / BACKUP_ROOT
    if not parent.is_dir():
        raise UpgradeError("Nenhum backup V3 encontrado.")
    dirs = sorted(
        [p for p in parent.iterdir()
         if p.is_dir() and (p / "manifest.json").is_file()],
        reverse=True,
    )
    if not dirs:
        raise UpgradeError("Nenhum backup V3 valido encontrado.")
    return dirs[0]

def restore(root: Path, dry_run=False):
    src = latest_backup(root)
    manifest = json.loads((src / "manifest.json").read_text(encoding="utf-8"))
    log(f"Restaurando {src.relative_to(root)}")
    for entry in manifest["files"]:
        rel = Path(entry["path"])
        dst = root / rel
        saved = src / rel
        if entry["exists"]:
            if dry_run:
                log(f"[dry-run] restauraria {rel}")
            else:
                atomic_write(dst, saved.read_bytes())
                log(f"  restaurado: {rel}")
        elif dst.exists():
            if dry_run:
                log(f"[dry-run] removeria {rel}")
            else:
                dst.unlink()
                log(f"  removido: {rel}")
    log("Restore concluido." if not dry_run else "Dry-run do restore concluido.")

def assert_safe_hash(path: Path, old_sha: str, new_sha: str, force: bool):
    got = sha256_file(path)
    if got in (old_sha, new_sha):
        return got
    if force:
        return got
    raise UpgradeError(
        f"{path} foi alterado desde os arquivos que voce me enviou.\n"
        f"Hash atual: {got}\n"
        "Parei para nao apagar modificacoes suas. "
        "Se quiser substituir mesmo assim, rode com --force."
    )

def install(root: Path, force=False, dry_run=False):
    scene_data, weather_data, effect_data = verify_embedded_payloads()

    scene_path = root / TARGET_SCENE
    weather_path = root / TARGET_WEATHER
    effect_path = root / TARGET_EFFECT
    constants_path = root / TARGET_CONSTANTS

    scene_hash = assert_safe_hash(scene_path, OLD_SCENE_SHA, NEW_SCENE_SHA, force)
    weather_hash = assert_safe_hash(weather_path, OLD_WEATHER_SHA, NEW_WEATHER_SHA, force)
    effect_hash = assert_safe_hash(effect_path, OLD_EFFECT_SHA, NEW_EFFECT_SHA, force)

    constants_text = constants_path.read_text(encoding="utf-8")
    patched_constants, dark_id, rain_id, count = patch_weather_constants(constants_text)

    changes = []
    if scene_hash != NEW_SCENE_SHA:
        changes.append(TARGET_SCENE)
    if weather_hash != NEW_WEATHER_SHA:
        changes.append(TARGET_WEATHER)
    if effect_hash != NEW_EFFECT_SHA:
        changes.append(TARGET_EFFECT)
    if constants_text != patched_constants:
        changes.append(TARGET_CONSTANTS)

    log("Dark Suicune V3 / Darkness weather")
    log(f"Repo: {root}")
    log(f"WEATHER_DARKNESS      = {dark_id}")
    log(f"WEATHER_DARKNESS_RAIN = {rain_id}")
    log(f"WEATHER_COUNT          = {count}")

    if not changes:
        log("\nTudo ja esta instalado.")
        return None

    b = backup(root, changes, dry_run=dry_run)
    log(f"Backup: {b.relative_to(root)}")

    writes = [
        (TARGET_SCENE, scene_data, NEW_SCENE_SHA),
        (TARGET_WEATHER, weather_data, NEW_WEATHER_SHA),
        (TARGET_EFFECT, effect_data, NEW_EFFECT_SHA),
        (TARGET_CONSTANTS, patched_constants.encode("utf-8"), None),
    ]

    for rel, data, expected in writes:
        if rel not in changes:
            log(f"  ok:         {rel}")
            continue
        if dry_run:
            log(f"  [dry-run] atualizaria: {rel}")
            continue
        atomic_write(root / rel, data)
        if expected is not None:
            got = sha256_file(root / rel)
            if got != expected:
                raise UpgradeError(
                    f"Falha de verificacao em {rel}: {got} != {expected}"
                )
        log(f"  atualizado: {rel}")
    return b

def git_diff_check(root: Path):
    git = shutil.which("git")
    if not git or not (root / ".git").exists():
        log("Git nao detectado; pulando git diff --check.")
        return
    cmd = [
        git, "diff", "--check", "--",
        str(TARGET_SCENE), str(TARGET_WEATHER),
        str(TARGET_EFFECT), str(TARGET_CONSTANTS),
    ]
    log("\nVerificando whitespace...")
    if subprocess.run(cmd, cwd=root).returncode != 0:
        raise UpgradeError("git diff --check encontrou um problema.")

def build(root: Path, jobs: int):
    make = shutil.which("make")
    if not make:
        raise UpgradeError("make nao encontrado no PATH.")
    cmd = [make, f"-j{jobs}"]
    log("\nCompilando: " + " ".join(cmd))
    rc = subprocess.run(cmd, cwd=root).returncode
    if rc != 0:
        raise UpgradeError(f"Build falhou com codigo {rc}.")
    log("\nBuild concluido com sucesso.")

def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--root", type=Path, default=Path.cwd())
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--no-build", action="store_true")
    p.add_argument("--jobs", type=int, default=8)
    p.add_argument("--force", action="store_true")
    p.add_argument("--restore-latest", action="store_true")
    return p.parse_args()

def main():
    args = parse_args()
    root = args.root.expanduser().resolve()
    validate_root(root)

    if args.restore_latest:
        restore(root, dry_run=args.dry_run)
        return 0

    b = install(root, force=args.force, dry_run=args.dry_run)
    if args.dry_run:
        log("\nDry-run concluido. Nenhum arquivo foi alterado.")
        return 0

    git_diff_check(root)
    if not args.no_build:
        try:
            build(root, args.jobs)
        except UpgradeError:
            if b is not None:
                log("\nPara desfazer:")
                log("  python3 upgrade_dark_suicune_darkness_v3.py --restore-latest")
            raise

    log("\nPronto.")
    log("Use em scripts/mapas:")
    log("  setweather WEATHER_DARKNESS")
    log("  setweather WEATHER_DARKNESS_RAIN")
    if b is not None:
        log(f"Backup: {b.relative_to(root)}")
    return 0

if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except UpgradeError as e:
        print(f"\nERRO: {e}", file=sys.stderr)
        raise SystemExit(1)
