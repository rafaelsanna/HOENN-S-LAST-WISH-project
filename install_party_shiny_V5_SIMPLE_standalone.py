def unpack(s): return zlib.decompress(base64.b85decode(s.encode("ascii")))

def sha_bytes(b): return hashlib.sha256(b).hexdigest()

def sha_file(p):
    h=hashlib.sha256()
    with p.open("rb") as f:
        for chunk in iter(lambda:f.read(1024*1024), b""):
            h.update(chunk)
    return h.hexdigest()

def root_for(explicit):
    if explicit:
        root=Path(explicit).expanduser().resolve()
    else:
        start=Path.cwd().resolve()
        root=next((p for p in [start,*start.parents] if (p/"Makefile").is_file() and (p/C_REL).is_file()), start)
    if not (root/"Makefile").is_file() or not (root/C_REL).is_file():
        raise SystemExit("ERRO: raiz do projeto inválida.")
    return root

def make_backup(root, rels):
    stamp=datetime.now().strftime("%Y%m%d-%H%M%S")
    b=root/BACKUP_DIR/stamp
    manifest={"created":stamp,"files":{}}
    for rel in rels:
        src=root/rel
        existed=src.exists()
        manifest["files"][str(rel)]={"existed":existed,"sha256":sha_file(src) if existed and src.is_file() else None}
        if existed and src.is_file():
            dst=b/rel; dst.parent.mkdir(parents=True, exist_ok=True); shutil.copy2(src,dst)
    b.mkdir(parents=True, exist_ok=True)
    (b/"manifest.json").write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+"\n",encoding="utf-8")
    return b

def install(root, force):
    cdata, adata = unpack(C_PAYLOAD), unpack(ASSET_PAYLOAD)
    if sha_bytes(cdata)!=FINAL_SHA or sha_bytes(adata)!=ASSET_SHA:
        raise SystemExit("ERRO: payload interno corrompido.")
    tc, ta = root/C_REL, root/ASSET_REL
    current=sha_file(tc)
    if current==FINAL_SHA:
        print("C: V5 SIMPLE já instalada.")
        replace=False
    elif current in KNOWN:
        print(f"C: {KNOWN[current]} detectada -> atualizando para V5 SIMPLE.")
        replace=True
    elif force:
        print("AVISO: --force-replace ativo.")
        replace=True
    else:
        print("ERRO: party_menu.c desconhecido; nada foi sobrescrito.")
        print("Use --force-replace apenas se quiser substituição completa.")
        return False

    asset_copy = not ta.is_file() or sha_file(ta)!=ASSET_SHA
    rels=([C_REL] if replace else [])+([ASSET_REL] if asset_copy else [])
    if not rels:
        print("Nada para alterar."); return True

    b=make_backup(root,rels); print(f"Backup: {b}")
    if replace:
        tc.write_bytes(cdata); print(f"OK: {C_REL}")
    if asset_copy:
        ta.parent.mkdir(parents=True,exist_ok=True); ta.write_bytes(adata); print(f"OK: {ASSET_REL}")
    return True

def build(root,jobs):
    cmd=[shutil.which("make") or "make", f"-j{jobs}"]
    print("Build:"," ".join(cmd))
    return subprocess.run(cmd,cwd=root).returncode==0

def main():
    p=argparse.ArgumentParser()
    p.add_argument("--project")
    p.add_argument("--build",action="store_true")
    p.add_argument("--jobs",type=int,default=max(1,os.cpu_count() or 1))
    p.add_argument("--force-replace",action="store_true")
    a=p.parse_args()
    root=root_for(a.project); print(f"Projeto: {root}")
    if not install(root,a.force_replace): return 2
    if a.build and not build(root,a.jobs): return 3
    print("Party Shiny V5 SIMPLE instalada.")
    return 0

if __name__=="__main__":
    raise SystemExit(main())
